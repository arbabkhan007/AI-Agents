"""Workbook level defined names that point at the register sheets.

The fixed drop-downs - service categories, payment terms, expense
categories - define their own names over on `Settings & Lists`. The
names here are the ones that have to follow live data: the customers
you actually have, the properties you actually maintain, the crew who
actually turn up. Each covers the full prepared range, including entries after blank rows.
Dropdowns can therefore include blank choices.

The ten at the top are the join keys, and they are what make this a
connected workbook rather than twenty-three separate lists: a job
points at a Property ID, the property points at a Customer ID, and an
invoice points back at both. Every one of those cells is a drop-down
rather than free text in every tab except the one where the ID is
created, because a mistyped ID is a row that quietly stops being part
of the business.

The rest are there so that you can write your own formulas against
this workbook without hunting for column letters. ``SUM(JobCharge)``
works from any sheet, and goes on working after you insert a column.
"""

