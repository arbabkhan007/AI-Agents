def purchase_rows(cfg: Config) -> List[Dict]:
    rng = _rng(cfg)
    inv = inventory_rows(cfg)
    rows: List[Dict] = []
    for back in range(0, 180, 7):
        d = cfg.today - dt.timedelta(days=back)
        p = rng.choice(inv)
        status = "Received" if back > 10 else rng.choice(
            ["Received", "Ordered"])
        rows.append(dict(
            date=d, po=f"PO-{1000 + back}", supplier=p["supplier"],
            product=p["name"], qty=rng.randint(6, 24),
            unit_cost=p["unit_cost"], status=status,
            received_date=d + dt.timedelta(days=3)
            if status == "Received" else None, notes=""))
    rows.sort(key=lambda r: r["date"], reverse=True)
    return rows[:cfg.row_count("14 Suppliers & Purchases")]


