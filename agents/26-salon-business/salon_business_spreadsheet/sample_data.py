def service_rows(cfg: Config) -> List[Dict]:
    rows = []
    for cat, name, dur, price, pcost, lcost in SERVICES:
        rows.append(dict(
            category=cat, name=name,
            description=f"{name} - consultation included",
            duration=dur, price=float(price),
            addon=round(price * 0.15, 2) if cat in ("Hair", "Nails") else 0,
            promo=round(price * 0.85, 2) if dur <= 60 else 0,
            product_cost=float(pcost), labour_cost=float(lcost),
            taxable="Yes", active="Yes", planned=0))
    return rows


def inventory_rows(cfg: Config) -> List[Dict]:
    rng = _rng(cfg)
    rows = []
    for i, (cat, name, cost, retail, sup) in enumerate(PRODUCTS):
        opening = rng.randint(4, 24) if cat == "Retail" else rng.randint(2, 10)
        rows.append(dict(
            sku=f"SKU-{i + 1:03d}", name=name, category=cat, supplier=sup,
            unit_cost=float(cost), retail=float(retail), taxable="Yes",
            opening=opening, used=rng.randint(0, 4), wasted=rng.randint(0, 1),
            adjusted=0, min_level=max(2, opening // 3),
            expiry=cfg.today + dt.timedelta(days=rng.randint(90, 540))
            if cat == "Backbar" else None,
            batch=f"B{rng.randint(100, 999)}", notes=""))
    return rows


