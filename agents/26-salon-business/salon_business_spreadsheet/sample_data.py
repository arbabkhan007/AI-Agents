def _service_plan(cfg: Config):
    """staff -> list of (service dict) they perform."""
    by_cat = {
        "Ava Reyes": ["Hair"], "Jon Park": ["Hair"],
        "Maya Chen": ["Nails", "Waxing"],
        "Lena Ford": ["Lashes", "Brows", "Skincare"],
    }
    out = {}
    for staff, cats in by_cat.items():
        out[staff] = [s for s in SERVICES if s[1 - 1] in cats]
    return out


def appointment_rows(cfg: Config) -> List[Dict]:
    rng = _rng(cfg)
    names = _client_names(cfg)
    plan = _service_plan(cfg)
    staff_cycle = list(plan.keys())
    rows: List[Dict] = []
    day = cfg.today - dt.timedelta(days=300)
    ci = 0
    while day < cfg.today - dt.timedelta(days=1):
        if day.weekday() == 6:
            day += dt.timedelta(days=1)
            continue
        for _ in range(rng.randint(2, 4)):
            staff = rng.choice(staff_cycle)
            svc = rng.choice(plan[staff])
            status = rng.choices(
                ["Completed", "Cancelled", "No-show"],
                weights=[86, 8, 6])[0]
            rows.append(dict(
                date=day, time=dt.time(9 + rng.randint(0, 8),
                                       rng.choice([0, 30])),
                client=names[ci % len(names)],
                staff=staff, service=svc[1], status=status,
                deposit=rng.choice([0, 0, 20.0, 30.0])
                if svc[3] >= 90 else 0,
                source=rng.choice(["Instagram", "Phone", "Walk-in",
                                   "Website", "Referral"]),
                walkin="Yes" if rng.random() < 0.08 else "No",
                cancel_reason=rng.choice(["Work", "Ill", "Childcare", ""])
                if status == "Cancelled" else "",
                rescheduled="", notes=""))
            ci += 1
        day += dt.timedelta(days=1)
    # open bookings in the next two weeks
    for k in range(12):
        d = cfg.today + dt.timedelta(days=1 + k)
        if d.weekday() == 6:
            continue
        staff = rng.choice(staff_cycle)
        svc = rng.choice(plan[staff])
        rows.append(dict(
            date=d, time=dt.time(10 + rng.randint(0, 6),
                                 rng.choice([0, 30])),
            client=names[rng.randrange(len(names))], staff=staff,
            service=svc[1], status=rng.choice(["Booked", "Confirmed"]),
            deposit=20.0 if svc[3] >= 90 else 0, source="Instagram",
            walkin="No", cancel_reason="", rescheduled="", notes=""))
    rows.sort(key=lambda r: (r["date"], r["time"]))
    return rows[:cfg.row_count("3 Appointment Planner")]


def sales_rows(cfg: Config) -> List[Dict]:
    rng = _rng(cfg)
    appts = appointment_rows(cfg)
    inv = inventory_rows(cfg)
    retail = [p for p in inv if p["category"] == "Retail"]
    prices = {s[1]: float(s[3]) for s in SERVICES}
    rows: List[Dict] = []
    for a in appts:
        if a["status"] != "Completed":
            continue
        price = prices[a["service"]]
        disc = rng.choice([0, 0, 0, 5.0, 10.0])
        rows.append(dict(
            date=a["date"], client=a["client"], staff=a["staff"],
            type="Service", item=a["service"], qty=1, discount=disc,
            refund=0, method=rng.choices(
                ["Card", "Cash", "Bank Transfer"],
                weights=[62, 30, 8])[0],
            paid=round(price - disc, 2), notes=""))
        if rng.random() < 0.35:
            p = rng.choice(retail)
            qty = rng.randint(1, 2)
            rows.append(dict(
                date=a["date"], client=a["client"], staff=a["staff"],
                type="Retail", item=p["name"], qty=qty, discount=0,
                refund=0, method="Card",
                paid=round(p["retail"] * qty, 2), notes=""))
    # a couple of refunds and one part payment for realism
    if rows:
        rows[-3]["refund"] = 15.0
        rows[-3]["notes"] = "Price match honoured"
        rows[-1]["paid"] = round(rows[-1]["paid"] - 20, 2)
        rows[-1]["notes"] = "Balance on account - chase this week"
    rows.sort(key=lambda r: r["date"])
    return rows[:cfg.row_count("6 Sales & Transactions")]


def payment_rows(cfg: Config) -> List[Dict]:
    sales = sales_rows(cfg)
    appts = appointment_rows(cfg)
    rows: List[Dict] = []
    for i, s in enumerate(sales):
        rows.append(dict(
            date=s["date"], client=s["client"], kind="Payment",
            method=s["method"], applied_to=f"T-{i + 1:04d}",
            amount=s["paid"], notes=""))
    for i, a in enumerate(appts):
        if a["status"] in ("Booked", "Confirmed") and a["deposit"]:
            rows.append(dict(
                date=a["date"] - dt.timedelta(days=2), client=a["client"],
                kind="Deposit", method="Card",
                applied_to=f"A-{i + 1:04d}", amount=a["deposit"],
                notes="Held against booking"))
    rows.append(dict(date=cfg.today - dt.timedelta(days=9),
                     client=sales[-3]["client"], kind="Refund",
                     method="Card", applied_to=f"T-{len(sales) - 2:04d}",
                     amount=15.0, notes="Price match refunded"))
    rows.sort(key=lambda r: r["date"])
    return rows[:cfg.row_count("7 Payments & Deposits")]


def payroll_rows(cfg: Config) -> List[Dict]:
    rng = _rng(cfg)
    staff = [s["name"] for s in staff_rows(cfg)]
    rows: List[Dict] = []
    for back in range(12):
        base = cfg.today - dt.timedelta(days=14 * back)
        period = f"{base.year}-{base.month:02d} H{2 if back % 2 else 1}"
        for name in staff:
            if name == "Lena Ford":
                continue          # contractor invoices, not payroll
            hours = round(rng.uniform(55, 80), 1)
            tips_in = round(rng.uniform(40, 140), 2)
            rows.append(dict(
                period=period, date=base - dt.timedelta(days=base.day % 14),
                staff=name, hours=hours, tips_in=tips_in,
                tips_out=tips_in, notes=""))
    rows.sort(key=lambda r: r["date"], reverse=True)
    return rows[:cfg.row_count("10 Payroll & Tips")]


